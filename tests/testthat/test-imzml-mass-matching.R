test_that("processed imzML matches measured precursors and fragments within ppm windows", {
  skip_if_not("local_mocked_bindings" %in% getNamespaceExports("testthat"))
  work <- tempfile()
  dir.create(work)
  on.exit(unlink(work, recursive = TRUE), add = TRUE)

  mz <- c(60.00390625, 80.00390625, 100.00390625, 105)
  axis <- round(mz, 2)
  values <- rbind(2 * (1:8), 3 * (1:8), 5 * (1:8), rep(100, 8))
  image <- Cardinal::MSImagingExperiment(values, featureData = Cardinal::MassDataFrame(mz),
                                         centroided = TRUE)
  path <- file.path(work, "processed.imzML")
  suppressWarnings(Cardinal::writeMSIData(methods::as(image, "MSProcessedImagingExperiment"), path))
  object <- read_msi_data(path, "imzml", bin_digits = 2L, min_pixels = 1L)
  expect_equal(object@variable_info$mz, axis)
  expect_equal(object@variable_info$observed_mz_full, mz)
  expect_true(all(abs(axis[1:3] - mz[1:3]) / mz[1:3] * 1e6 > 15))
  object <- define_roi(object, data.frame(x = 1:8, y = 1,
    region = rep(c("pericentral", "periportal"), each = 4)))

  # Each mass representation has a distinct control compound in both libraries.
  compounds <- c("HMDB0000001", "HMDB0000002")
  spectra <- data.frame(spectrum_id = c("measured", "axis"), candidate_id = compounds,
    compound_id = compounds, candidate_name = c("Measured", "Axis"), library_source = "test",
    database_source = "test", precursor_mz = c(mz[3], axis[3]), formula = c("C4H6O3", "C5H10O2"),
    polarity = "negative", adduct = "[M-H]-", inchikey = NA_character_, smiles = NA_character_)
  peaks <- data.frame(spectrum_id = rep(spectra$spectrum_id, each = 2),
    candidate_id = rep(compounds, each = 2), peak_mz = c(mz[1:2], axis[1:2]),
    intensity_raw = rep(c(2, 3), 2), intensity_sum1 = rep(c(0.4, 0.6), 2))
  ms2 <- list(library_spectrum_table = spectra, library_peak_table = peaks)
  ms2$flash_entropy_index <- `56_build_flash_entropy_index`(ms2)$peak_index
  ms2_path <- file.path(work, "ms2.rds")
  saveRDS(ms2, ms2_path)
  ms1_path <- file.path(work, "ms1.rds")
  saveRDS(data.frame(HMDB.ID = compounds, Compound.Name = spectra$candidate_name,
    source_Lab_IDs = compounds, Adduct = "[M-H]-", Ion.Mode = "negative",
    theoretical_mz = spectra$precursor_mz, Formula = spectra$formula), ms1_path)
  vector_path <- file.path(work, "ids.tsv")
  writeLines(c("HMDB_ID", compounds), vector_path)
  config_path <- file.path(work, "config.yaml")
  yaml::write_yaml(list(run = list(sample_mode = "standard_mixture"),
    flash_entropy = list(top_n_candidates = 2, top_n_spectra = 2, top_n_compounds = 2,
      max_spectra_per_compound = 1, min_matches = 2, min_score = 0),
    library = list(min_peaks = 2), reverse_matching = list(min_reverse_masked_cosine = 0),
    annotation = list(q_value_cutoff = 0.05, candidate_sas_cutoff = 0.75,
      candidate_source_for_step7 = "reverse_match_filtered"),
    mfc = list(ms1_library_path = ms1_path, ms1_mz_source = "cardinal_measured_feature_axis",
      ms1_ppm = 10, ppm_sigma = 5, max_candidates_per_feature = 5,
      ms1_matching_scope = "all_filtered_features", use_isotope = FALSE)), config_path)
  resource <- function(path) list(path = path, sha256 = digest::digest(file = path, algo = "sha256"))
  lock <- list(ms2_library = resource(ms2_path), ms1_library = resource(ms1_path),
    vector_ids = resource(vector_path), adp_config = resource(config_path),
    ms1_project_root = list(path = work))
  testthat::local_mocked_bindings(.msi_locked_resources = function(lock_path) lock,
                                  .package = "msidataset")

  measured <- generate_pseudo_ms2(object)
  measured_pairs <- measured@process_info$generate_pseudo_ms2$result
  expect_equal(unique(measured_pairs$precursor_mz[measured_pairs$precursor_feature_id == "F003"]), mz[3])
  expect_equal(measured_pairs$fragment_mz[measured_pairs$precursor_feature_id == "F003"], mz[1:2])

  fallback <- object
  fallback@variable_info$observed_mz_full <- NULL
  fallback <- generate_pseudo_ms2(fallback)
  # Exercise saved pseudo-MS2 pairs generated by the previous release.
  measured@process_info$generate_pseudo_ms2 <- fallback@process_info$generate_pseudo_ms2
  expect_equal(fallback@process_info$generate_pseudo_ms2$result$fragment_mz[
    measured_pairs$precursor_feature_id == "F003"], axis[1:2])

  compare_matches <- function(input, masses, spectrum_id, compound, directory) {
    dir.create(directory)
    matched <- match_spectral_library(input, list(output_dir = directory, workers = 1L))
    result <- matched@process_info$match_spectral_library$result
    expect_identical(result$status, "OK")
    expect_equal(result$step6@variable_info$observed_mz_full, masses)
    expect_identical(unique(result$step6@annotation_results$flash_entropy_spectrum_hits$spectrum_id), spectrum_id)
    expect_identical(unique(result$step6@annotation_results$reverse_match$spectrum_id), spectrum_id)
    scored <- calculate_mfc(matched, output_dir = directory)
    result <- scored@process_info$calculate_mfc$result
    expect_identical(result$status, "OK")
    expect_identical(unique(result$candidates$HMDB_ID), compound)
    ms1 <- read.csv(file.path(directory, "tables", "module8_ms1_only_candidates.csv"), check.names = FALSE)
    expect_identical(unique(ms1$HMDB.ID), compound)
    expect_equal(ms1$ms1_feature_mz, masses[3])
    expect_equal(ms1$ppm_error, 0, tolerance = 1e-6)
    matched
  }
  matched <- compare_matches(measured, mz, "measured", compounds[1], file.path(work, "measured"))
  fallback <- compare_matches(fallback, axis, "axis", compounds[2], file.path(work, "axis"))

  old_step6 <- fallback@process_info$match_spectral_library$result$step6
  stale <- calculate_mfc(matched, step6 = old_step6, output_dir = work)
  expect_identical(stale@process_info$calculate_mfc$result$status, "UNRESOLVED_STEP6_MZ")
})
