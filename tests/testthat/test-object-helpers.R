test_that("object helpers preserve data and repeated process results", {
  path <- tempfile(fileext = ".csv")
  writeLines(c("1,2,100,5,10", "2,2,200,7,11"), path)
  x <- read_msi_data(path, mz = c(50, 60))
  x <- define_roi(x, data.frame(x = c(1, 2), y = c(2, 2), region = c("periportal", "pericentral")))
  expect_invisible(.msidataset_validate(x, require_roi = TRUE, require_mz = TRUE))
  i <- .msidataset_inputs(x, TRUE, TRUE)
  expect_equal(unname(i$intensity), matrix(c(5, 7, 10, 11), nrow = 2))
  y <- .msidataset_append_step(x, "example", data.frame(value = 1))
  y <- .msidataset_append_step(y, "example", data.frame(value = 2))
  expect_equal(y@process_info$example$result$value, 1)
  expect_equal(y@process_info$example_2$result$value, 2)
  expect_identical(y@expression_data, x@expression_data)
  bad <- x; bad@sample_info$sample_id <- rev(bad@sample_info$sample_id)
  expect_error(.msidataset_validate(bad), "identifiers")
})

test_that("object adapters retain DE and pseudo-MS2 results on one object", {
  path <- tempfile(fileext = ".csv")
  xy <- expand.grid(x = seq_len(10), y = seq_len(6))
  signal <- seq_len(nrow(xy))
  input <- cbind(xy, tic = 100, precursor = signal * 2, fragment = signal)
  utils::write.table(input, path, sep = ",", row.names = FALSE, col.names = FALSE)
  x <- read_msi_data(path, mz = c(100, 50))
  x <- define_roi(x, data.frame(xy, region = rep(c("periportal", "pericentral"), each = 30)))
  x <- detect_de_features(x)
  x <- generate_pseudo_ms2(x)
  expect_true(all(c("read_msi_data", "define_roi", "detect_de_features", "generate_pseudo_ms2") %in% names(x@process_info)))
  expect_equal(nrow(x@process_info$detect_de_features$result), 2)
  expect_equal(nrow(x@process_info$generate_pseudo_ms2$result), 1)
})

test_that("object adapters retain and flag invalid pixel values", {
  path <- tempfile(fileext = ".csv")
  writeLines(c("1,1,100,2,4", "2,1,100,4,8"), path)
  x <- read_msi_data(path, mz = c(100, 50))
  x <- define_roi(x, data.frame(x = c(1, 2), y = c(1, 1), region = c("periportal", "pericentral")))
  x@sample_info$tic[1] <- NA_real_
  y <- generate_pseudo_ms2(x)
  expect_identical(y@process_info$generate_pseudo_ms2$result$status, "UNRESOLVED_INPUT")
  expect_equal(y@process_info$generate_pseudo_ms2$result$problems$invalid_tic, 1L)
  expect_equal(nrow(y@sample_info), 2)
  expect_identical(y@expression_data, x@expression_data)
})

test_that("redefining an ROI preserves the previous labels and history", {
  path <- tempfile(fileext = ".csv")
  writeLines(c("1,1,100,2", "2,1,100,4"), path)
  x <- read_msi_data(path, mz = 50)
  x <- define_roi(x, data.frame(x = c(1, 2), y = c(1, 1), region = c("old1", "old2")))
  x <- define_roi(x, data.frame(x = c(1, 2), y = c(1, 1), region = c("new1", "new2")))
  expect_equal(x@process_info$define_roi_2$result$previous_region, c("old1", "old2"))
  expect_equal(x@sample_info$region, c("new1", "new2"))
  expect_true(all(c("define_roi", "define_roi_2") %in% names(x@process_info)))
})
