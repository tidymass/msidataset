test_that('step56 validates configuration and retains unresolved upstream evidence', {
  samples <- data.frame(sample_id=c('s1','s2'),class='unassigned',x=c(1,2),y=c(1,1),tic=c(1,1))
  vars <- data.frame(variable_id=c('a','b'),mz=c(100,80))
  e <- data.frame(s1=c(1,2),s2=c(2,3),row.names=c('a','b'),check.names=FALSE)
  x <- massdataset::create_mass_dataset(e,samples,vars)
  x <- define_roi(x,data.frame(x=c(1,2),y=c(1,1),region=c('PC','PP')))
  expect_error(match_spectral_library(x,list(output_dir=tempdir())),'generate_pseudo_ms2')
  expect_error(match_spectral_library(x,list(output_dir='missing')),'output_dir')
  x@process_info$generate_pseudo_ms2 <- list(result=list(status='UNRESOLVED_INPUT'))
  y <- match_spectral_library(x,list(output_dir=tempdir()))
  expect_identical(y@process_info$match_spectral_library$result$status,'UNRESOLVED_PSEUDO')
  expect_identical(y@process_info$generate_pseudo_ms2,x@process_info$generate_pseudo_ms2)
  y <- calculate_mfc(y,output_dir=tempdir())
  expect_identical(y@process_info$calculate_mfc$result$status,'UNRESOLVED_STEP6')
})
