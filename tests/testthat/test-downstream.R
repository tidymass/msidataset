test_that("MFC embedding preserves candidates and flags unavailable features", {
  path <- tempfile(); dir.create(path)
  on.exit(unlink(path, recursive = TRUE))
  jsonlite::write_json(list(shape=c(3L, 2L),dtype="float32",byte_order="little",order="C"), file.path(path,"meta.json"), auto_unbox=TRUE)
  ids <- data.frame(row=0:2,HMDB_ID=c("A","B","C"),name=c("a","b","c"),taxonomy_path="",card_completeness="FULL")
  write.table(ids,file.path(path,"ids.tsv"),sep="\t",row.names=FALSE,quote=FALSE)
  con<-file(file.path(path,"embeddings.f32"),"wb"); writeBin(as.numeric(c(1,0,0,1,-1,0)),con,size=4,endian="little"); close(con)
  cand<-data.frame(feature_id=c("f1","f1","f2"),HMDB_ID=c("A","B","missing"),mfc_priority_score=c(1,3,2))
  e<-embed_features(cand,path,c("f1","f2","f3"))
  expect_equal(e$feature_ids,"f1")
  expect_equal(unname(e$unit[1,]),c(1,3)/sqrt(10))
  expect_equal(e$coverage$status,c("OK","LOW_COVERAGE","NO_CANDIDATE"))
  expect_equal(nrow(cand),3)
  reps<-data.frame(cluster_id=0L,feature_id="f1")
  n<-retrieve_neighbors(e,reps,path,block_rows=2L)
  expect_equal(n$neighbors$HMDB_ID,c("B","A","C"))
  expect_equal(n$merged$HMDB_ID,c("B","A","C"))
})

test_that("representatives select a true member and mark small clusters", {
  a<-matrix(c(1,0, .99,.1, .98,.2, .97,.25, .96,.28, 0,1),ncol=2,byrow=TRUE)
  rownames(a)<-letters[1:6]
  m<-data.frame(feature_id=letters[1:6],cluster_id=c(rep(0,5),1))
  r<-select_representatives(a,m)
  expect_equal(nrow(r),5)
  expect_equal(r$role,c("center",rep("nearest",4)))
  expect_true(all(r$feature_id %in% letters[1:5]))
  expect_equal(attr(r,"issues")[[1]]$status,"SMALL_CLUSTER_LT5")
})
